function createTemplateDocument(definition) {
  const elements = [];
  const nodeIds = [];
  const arrowIds = [];
  const startX = 90;
  const nodeY = 225;
  const nodeWidth = 150;
  const nodeHeight = 90;
  const gap = 75;
  for (const [index, label] of definition.labels.entries()) {
    const nodeId = `${definition.id}-node-${index + 1}`;
    const textId = `${definition.id}-label-${index + 1}`;
    const x = startX + index * (nodeWidth + gap);
    nodeIds.push(nodeId, textId);
    elements.push(
      rectangle(nodeId, x, nodeY, nodeWidth, nodeHeight, definition.accent, textId),
      text(textId, x + 15, nodeY + 32, nodeWidth - 30, label, nodeId),
    );
    if (index > 0) {
      const previousNodeId = `${definition.id}-node-${index}`;
      const arrowId = `${definition.id}-arrow-${index}`;
      arrowIds.push(arrowId);
      elements.push(arrow(arrowId, x - gap, nodeY + nodeHeight / 2, gap, previousNodeId, nodeId));
    }
  }
  const timeline = {
    id: `${definition.id}-timeline`,
    name: `${definition.title} animation`,
    duration: 5_000,
    fps: 60,
    tracks: [],
  };
  const actions = [
    createAnimationAction({
      id: `${definition.id}-reveal`,
      type: 'fade',
      preset: 'fade',
      targetIds: nodeIds,
      timing: {
        startMs: 0,
        durationMs: 420,
        staggerMs: 90,
        startMode: 'absolute',
      },
      easing: 'easeOut',
      parameters: {},
    }),
    createAnimationAction({
      id: `${definition.id}-connections`,
      type: 'draw',
      preset: 'draw',
      targetIds: arrowIds,
      timing: {
        startMs: 360,
        durationMs: 520,
        staggerMs: 150,
        startMode: 'absolute',
      },
      easing: 'easeInOut',
      parameters: {},
    }),
  ];
  const compiled = compileManagedActions(timeline, [], actions);
  return parseProjectDocument({
    version: PROJECT_VERSION,
    metadata: {
      id: `template-${definition.id}`,
      name: definition.title,
      createdAt: generatedAt,
      updatedAt: generatedAt,
    },
    scene: {
      elements,
      appState: { viewBackgroundColor: '#ffffff' },
      files: {},
    },
    timeline: compiled.timeline,
    playback: {
      clipStart: 0,
      clipEnd: 3_500,
      cameraFrame: {
        aspectRatio: definition.aspectRatio,
        width: 960,
        x: 480,
        y: 270,
      },
    },
    authoring: {
      version: 1,
      documentRevision: 1,
      timelineRevision: 1,
      actions: compiled.actions,
    },
    preferredWorkspace: 'magic',
  });
}

function baseElement(id, type, x, y, width, height) {
  return {
    id,
    type,
    x,
    y,
    width,
    height,
    angle: 0,
    strokeColor: '#1e1e1e',
    backgroundColor: 'transparent',
    fillStyle: 'solid',
    strokeWidth: 2,
    strokeStyle: 'solid',
    roughness: 1,
    opacity: 100,
    groupIds: [],
    frameId: null,
    index: null,
    roundness: null,
    seed: hashNumber(id),
    version: 1,
    versionNonce: hashNumber(`${id}-version`),
    isDeleted: false,
    boundElements: null,
    updated: 1,
    link: null,
    locked: false,
  };
}

function rectangle(id, x, y, width, height, accent, textId) {
  return {
    ...baseElement(id, 'rectangle', x, y, width, height),
    strokeColor: accent,
    backgroundColor: `${accent}22`,
    roundness: { type: 3 },
    boundElements: [{ id: textId, type: 'text' }],
  };
}

function text(id, x, y, width, value, containerId) {
  return {
    ...baseElement(id, 'text', x, y, width, 25),
    strokeColor: '#1e1e1e',
    text: value,
    fontSize: 20,
    fontFamily: 5,
    textAlign: 'center',
    verticalAlign: 'middle',
    containerId,
    originalText: value,
    autoResize: true,
    lineHeight: 1.25,
  };
}

function arrow(id, x, y, width, startId, endId) {
  return {
    ...baseElement(id, 'arrow', x, y, width, 0),
    points: [
      [0, 0],
      [width, 0],
    ],
    startBinding: {
      elementId: startId,
      focus: 0,
      gap: 1,
      fixedPoint: [1, 0.5],
    },
    endBinding: {
      elementId: endId,
      focus: 0,
      gap: 1,
      fixedPoint: [0, 0.5],
    },
    startArrowhead: null,
    endArrowhead: 'arrow',
    lastCommittedPoint: null,
    elbowed: false,
  };
}

function createPoster(definition) {
  const cards = definition.labels
    .map((label, index) => {
      const x = 55 + index * 225;
      return `<rect x="${x}" y="225" width="175" height="90" rx="18" fill="#ffffff" stroke="${definition.accent}" stroke-width="4"/><text x="${x + 87.5}" y="278" text-anchor="middle" font-family="system-ui,sans-serif" font-size="22" font-weight="650" fill="#1f2937">${escapeXml(label)}</text>${index < definition.labels.length - 1 ? `<path d="M ${x + 175} 270 H ${x + 215}" stroke="${definition.accent}" stroke-width="5"/><path d="m ${x + 207} 262 10 8-10 8" fill="none" stroke="${definition.accent}" stroke-width="5"/>` : ''}`;
    })
    .join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" width="960" height="540" viewBox="0 0 960 540" role="img" aria-labelledby="title desc"><title id="title">${escapeXml(definition.title)}</title><desc id="desc">${escapeXml(definition.description)}</desc><rect width="960" height="540" fill="#f8f9fa"/><circle cx="870" cy="70" r="120" fill="${definition.accent}" opacity=".08"/><text x="55" y="90" font-family="system-ui,sans-serif" font-size="18" font-weight="700" letter-spacing="2" fill="${definition.accent}">EXCALIMATE TEMPLATE</text><text x="55" y="145" font-family="system-ui,sans-serif" font-size="38" font-weight="750" fill="#111827">${escapeXml(definition.title)}</text>${cards}<text x="55" y="460" font-family="system-ui,sans-serif" font-size="18" fill="#4b5563">Editable diagram and managed timeline actions</text></svg>`;
}

function sha256(value) {
  return createHash('sha256').update(value).digest('hex');
}

function hashNumber(value) {
  return Number.parseInt(sha256(value).slice(0, 8), 16);
}

function escapeXml(value) {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&apos;');
}
